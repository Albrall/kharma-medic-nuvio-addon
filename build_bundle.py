#!/usr/bin/env python3
"""
build_bundle.py
---------------
يولّد تلقائياً:
  1. lib/addon_data.js      (لاستخدام Vercel Serverless + Node server.js)
  2. cloudflare-worker.js   (ملف واحد متكامل لـ Cloudflare Workers بدون أي اعتماديات خارجية)
"""
import glob
import hashlib
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))


def main():
    manifest = json.load(open(os.path.join(ROOT, "manifest.json"), encoding="utf-8"))

    catalogs = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "catalog/movie/*.json"))):
        cid = os.path.splitext(os.path.basename(p))[0]
        catalogs[cid] = json.load(open(p, encoding="utf-8"))

    metas = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "meta/movie/*.json"))):
        mid = os.path.splitext(os.path.basename(p))[0]
        metas[mid] = json.load(open(p, encoding="utf-8"))

    base_streams = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "stream/movie/*.json"))):
        sid = os.path.splitext(os.path.basename(p))[0]
        base_streams[sid] = json.load(open(p, encoding="utf-8"))

    tb_map_path = os.path.join(ROOT, "torbox_map.json")
    torbox_map = (
        json.load(open(tb_map_path, encoding="utf-8"))
        if os.path.exists(tb_map_path)
        else {}
    )

    sessions = {}
    for m in catalogs["kharma_all"]["metas"]:
        item_id = m["id"]
        yt_id = item_id.replace("km_", "")
        desc_parts = (m.get("description") or "").split("\n\n")
        full_title = desc_parts[1].strip() if len(desc_parts) > 1 else m["name"]
        rel = m.get("releaseInfo") or ""
        hours_label = rel.split("•")[-1].strip() if "•" in rel else rel.strip()
        md5_watch = hashlib.md5(
            f"https://www.youtube.com/watch?v={yt_id}".encode("utf-8")
        ).hexdigest()
        md5_short = hashlib.md5(
            f"https://youtu.be/{yt_id}".encode("utf-8")
        ).hexdigest()
        sessions[yt_id] = {
            "ytId": yt_id,
            "id": item_id,
            "name": m["name"],
            "shortLabel": m["name"].split("(")[0].strip(),
            "fullTitle": full_title,
            "hoursLabel": hours_label,
            "md5Watch": md5_watch,
            "md5Short": md5_short,
        }

    bundle_obj = {
        "MANIFEST": manifest,
        "CATALOGS": catalogs,
        "METAS": metas,
        "BASE_STREAMS": base_streams,
        "SESSIONS": sessions,
        "TORBOX_MAP": torbox_map,
    }
    data_json = json.dumps(bundle_obj, ensure_ascii=False, indent=2)

    os.makedirs(os.path.join(ROOT, "lib"), exist_ok=True)
    addon_data_path = os.path.join(ROOT, "lib/addon_data.js")
    with open(addon_data_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build_bundle.py — do not edit manually\n")
        f.write(f"module.exports = {data_json};\n")

    # Build standalone single-file Cloudflare Worker (ES Module)
    resolver_src = open(
        os.path.join(ROOT, "lib/torbox_resolver.js"), encoding="utf-8"
    ).read()
    # Strip CommonJS export footer for ES module Worker
    resolver_body = re.sub(
        r"module\.exports\s*=\s*\{[\s\S]*?\};\s*$", "", resolver_src
    )

    worker_code = f"""// Auto-generated single-file Cloudflare Worker for Kharma Medic × TorBox Nuvio Addon
const ADDON_DATA = {data_json};

{resolver_body}

export default {{
  async fetch(request, env) {{
    const url = new URL(request.url);
    const clientIp =
      request.headers.get("cf-connecting-ip") ||
      request.headers.get("x-forwarded-for") ||
      "";
    const result = await handleAddonRequest(
      {{
        method: request.method,
        pathname: url.pathname,
        origin: url.origin,
        clientIp,
        env: env || {{}},
      }},
      ADDON_DATA
    );
    return new Response(result.method === "HEAD" ? null : result.body, {{
      status: result.status,
      headers: result.headers,
    }});
  }},
}};
"""
    worker_path = os.path.join(ROOT, "cloudflare-worker.js")
    with open(worker_path, "w", encoding="utf-8") as f:
        f.write(worker_code)

    print(
        f"✅ Built lib/addon_data.js and cloudflare-worker.js ({len(sessions)} sessions, {len(torbox_map)} mapped)."
    )


if __name__ == "__main__":
    main()
